function toQuestion(raw: Raw): HvhQuestion {
  const options: HvhOption[] = raw.o.map(([, label], i) => ({
    id: raw.o[i][0] || OPTION_IDS[i],
    label,
  }));
  return {
    id: raw.id,
    category: raw.c,
    axis: raw.ax,
    difficulty: raw.d,
    prompt: raw.q,
    sub: raw.s,
    options,
    sample: raw.p.slice(0, options.length),
  };
}

/** The built-in scenario bank, normalised and ready to play. */
export const QUESTIONS: HvhQuestion[] = RAW.map(toQuestion);

